// The operation set is always read from the exported OpenAPI graph.  This small policy chooses
// the deterministic hermetic probe for a declared response class; it is intentionally not a
// method/path inventory and therefore cannot drift independently from the Rust routes.
function preferredHttpStatus(key, operation) {
  const statuses = Object.keys(operation.responses)
    .map(Number)
    .sort((a, b) => a - b);
  const has = (status) => statuses.includes(status);
  const [method, path] = key.split(' ');
  if (has(409) && /google\/start/.test(path)) return 409;
  if (has(307)) return 307;
  if (has(400) && path.includes('/contract/')) return 400;
  if (has(404) && path.includes('/market-data')) return 404;
  if (has(404) && /\/(?:signals|strike-profile)$/.test(path)) return 404;
  if (has(400) && path === '/api/prices') return 400;
  if (has(422) && path === '/api/stream/prices') return 422;
  if (has(200) && path.endsWith('/progressive')) return 200;
  if (has(401) && path.endsWith('/settings')) return 401;
  if (
    has(403) &&
    (/^POST \/api\/positions\//.test(key) ||
      (method === 'GET' && path === '/api/book') ||
      (method === 'PUT' && path === '/api/scan/view') ||
      /\/broker\//.test(path) ||
      /\/auth\/(?:ai-key|grok)/.test(path))
  )
    return 403;
  if (has(422) && ['POST', 'PUT', 'DELETE'].includes(method)) return 422;
  if (
    has(502) &&
    /\/(?:price|ticker|candidate|recommendation|contract|market-data|signals|strike-profile)/.test(
      path,
    )
  )
    return 502;
  if (
    has(403) &&
    (/^POST \/api\/positions\//.test(key) ||
      (method === 'GET' && path === '/api/book') ||
      /\/broker\//.test(path) ||
      /\/auth\/(?:ai-key|grok)/.test(path))
  )
    return 403;
  if (
    has(401) &&
    (path.includes('_metrics') || path.includes('_research') || path.endsWith('/settings'))
  )
    return 401;
  if (has(400) && (path.includes('/prices') || path.includes('/contract/'))) return 400;
  if (has(404) && statuses.every((status) => status >= 400 || status === 404)) return 404;
  return has(200) ? 200 : statuses[0];
}

