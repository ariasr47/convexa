function buildBoundaryEvidence(parity) {
  const boundaries = {};
  for (const operation of parity.operations) {
    for (const boundary of operation.boundaries) {
      const expected = expectedResponseFor(
        operation.key,
        boundary.status,
        boundary.media_type,
        boundary.security_mode,
        boundary.header_names,
      );
      boundaries[boundary.test] = {
        operation: operation.key,
        status: boundary.status,
        media_type: boundary.media_type,
        header_names: boundary.header_names,
        header_value_policies: expected.header_value_policies,
        security_mode: boundary.security_mode,
        body_category: expected.body_category,
        body_valid: expected.body_valid,
        body_meaning: expected.body_meaning,
        body_schema: JSON.parse(boundary.body_schema_signature),
        effect_assertion: { durable: 'none', memory: 'none', cookie: 'none' },
      };
    }
  }
  return { schema_version: 2, boundaries };
}

function securityModeFor(operation) {
  const security = operation.security ?? [];
  if (security.length === 0) return 'public';
  if (security.length === 2) return 'optional-session';
  if (security[0]['session-cookie']) return 'session';
  if (security[0]['operator-token']) return 'operator-token';
  if (security[0]['oauth-state']) return 'oauth-state';
  fail('incomplete contract coverage', 'unknown Rust security mode');
}
function generateTypes(openapi) {
  failAt('typescript');
  const cli = join(TOOLCHAIN_ROOT, 'node_modules', 'openapi-typescript', 'bin', 'cli.js');
  if (!existsSync(cli))
    fail('generation tooling failure', 'openapi-typescript binary is not installed');
  const dir = mkdtempSync(join(ROOT, 'api-contract-temp-'));
  try {
    const source = join(dir, 'openapi.json'),
      out = join(dir, 'schema.ts');
    writeFileSync(source, json(openapi, files.openapi));
    run(process.execPath, [cli, source, '-o', out]);
    run(process.execPath, [prettierCli, '--write', '--parser', 'typescript', out]);
    return (
      header +
      readFileSync(out, 'utf8')
        .replace(/^\/\/.*\n/gm, '')
        .replace(/^\s+/, '')
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
function artifactManifest(bytes) {
  const keyForPath = {
    [files.openapi]: 'openapi',
    [files.parity]: 'parity',
    [files.baseline]: 'baseline',
    [files.schema]: 'schema',
  };
  const entries = requiredManifest
    .map(([path, kind, media_type, writer]) => ({
      path,
      kind,
      media_type,
      writer,
      sha256: sha(bytes[keyForPath[path]]),
    }))
    .sort((a, b) => a.path.localeCompare(b.path));
  return {
    schema_version: 1,
    notice: 'Generated from the Rust API contract. Do not edit generated artifacts.',
    regenerate_command: 'npm run api:contract:generate',
    check_command: 'npm run api:contract:check',
    owner: 'tools/api-contract.mjs',
    artifacts: entries,
  };
}
function authorityScan() {
  const roots = ['libs/api/src', 'apps/dashboard/src'];
  const generatedRoot = resolve(ROOT, 'libs/api/src/generated');
  const generated = new Set(
    [
      ...readFileSync(join(ROOT, files.schema), 'utf8').matchAll(
        /^\s{8}([A-Za-z][A-Za-z0-9]*): \{/gm,
      ),
    ].map(([, name]) => name),
  );
  const violations = [];
  const visit = (dir) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (/\.(ts|tsx)$/.test(entry.name) && !/\.(spec|test)\.(ts|tsx)$/.test(entry.name)) {
        if (resolve(path).startsWith(generatedRoot)) continue;
        const source = readFileSync(path, 'utf8');
        const repoPath = rel(path);
        if (
          !FACADE_FILES.has(repoPath) &&
          /(?:from|import\s*\()\s*['"][^'"]*generated\/schema/.test(source)
        )
          violations.push(`${repoPath}: generated deep import`);
        for (const [, name] of source.matchAll(/^export interface (\w+)/gm))
          if (generated.has(name)) violations.push(`${repoPath}: duplicate wire interface ${name}`);
        for (const [, name] of source.matchAll(/\b(?:const|let|var)\s+(\w+)\s*=\s*\{/g))
          if (generated.has(name)) violations.push(`${repoPath}: duplicate wire object ${name}`);
        if (/body\s*:\s*[^\n]+\s+as\s+components\[/.test(source))
          violations.push(`${repoPath}: unchecked generated HTTP body cast`);
      }
    }
  };
  roots.forEach((root) => visit(join(ROOT, root)));
  if (violations.length) fail('incomplete contract coverage', violations.sort().join(', '));
}
function candidate() {
  const doc = exportOpenapi();
  const ops = validateOpenapi(doc);
  const base = baseline();
  const expected = (base.operations ?? [])
    .map((x) => ({ method: x.method, path: x.path }))
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  if (JSON.stringify(ops) !== JSON.stringify(expected))
    fail(
      'incomplete contract coverage',
      `operation set differs from immutable baseline (${ops.length} vs ${expected.length})`,
    );
  const openapiBytes = Buffer.from(json(doc, files.openapi));
  const parityObject = buildParity(doc, ops, sha(openapiBytes));
  validateParity(parityObject, ops, doc);
  const bytes = {
    openapi: openapiBytes,
    parity: Buffer.from(json(parityObject, files.parity)),
    schema: Buffer.from(generateTypes(doc)),
  };
  bytes.evidence = Buffer.from(json(buildBoundaryEvidence(parityObject), files.evidence));
  failAt('candidate-compile');
  compileCandidateConsumers(bytes.schema);
  if (!bytes.schema.toString('utf8').startsWith(header))
    fail('invalid OpenAPI artifact', 'schema.ts header');
  for (const key of ['openapi', 'parity', 'schema']) scanArtifact(files[key], bytes[key]);
  bytes.manifest = Buffer.from(
    json(
      artifactManifest({ ...bytes, baseline: readFileSync(join(ROOT, files.baseline)) }),
      files.manifest,
    ),
  );
  return bytes;
}
function install(bytes) {
  failAt('install');
  const temp = mkdtempSync(join(ROOT, 'api-contract-install-'));
  const backups = new Map();
  const touched = new Set();
  try {
    for (const key of mutable) {
      const p = join(temp, key);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, bytes[key]);
    }
    for (const key of mutable) {
      const target = join(ROOT, files[key]);
      const backup = join(temp, `${key}.previous`);
      mkdirSync(dirname(target), { recursive: true });
      if (existsSync(target)) {
        renameSync(target, backup);
        backups.set(key, backup);
      }
      renameSync(join(temp, key), target);
      touched.add(key);
      if (process.env.API_CONTRACT_FAIL_AFTER_KEY === key)
        fail('generation tooling failure', `stage install after ${key} failed by test hook`);
    }
    rmSync(temp, { recursive: true, force: true });
  } catch (error) {
    for (const key of touched) {
      const target = join(ROOT, files[key]);
      if (existsSync(target)) rmSync(target, { force: true });
      const backup = backups.get(key);
      if (backup && existsSync(backup)) renameSync(backup, target);
    }
    for (const [key, backup] of backups) {
      const target = join(ROOT, files[key]);
      if (!existsSync(target) && existsSync(backup)) renameSync(backup, target);
    }
    rmSync(temp, { recursive: true, force: true });
    throw error;
  }
}
function check() {
  if (process.env.API_CONTRACT_MISSING_OUTPUT)
    fail('missing output', process.env.API_CONTRACT_MISSING_OUTPUT);
  if (process.env.API_CONTRACT_ZERO_OUTPUT)
    fail('zero-operation output', 'candidate OpenAPI contains no production operations');
  if (process.env.API_CONTRACT_UNSUPPORTED_CONSTRUCT)
    fail('unsupported schema construct', process.env.API_CONTRACT_UNSUPPORTED_CONSTRUCT);
  for (const key of ['openapi', 'parity', 'schema', 'manifest', 'baseline', 'evidence'])
    if (!existsSync(join(ROOT, files[key])))
      fail('missing output', `${files[key]}; run npm run api:contract:generate`);
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(join(ROOT, files.manifest), 'utf8'));
  } catch {
    fail('invalid OpenAPI artifact', 'manifest JSON');
  }
  if (manifest.schema_version !== 1 || !Array.isArray(manifest.artifacts))
    fail('invalid OpenAPI artifact', 'manifest schema');
  let committedOpenapi;
  try {
    committedOpenapi = JSON.parse(readFileSync(join(ROOT, files.openapi), 'utf8'));
  } catch {
    fail('invalid OpenAPI artifact', `${files.openapi}: JSON`);
  }
  const committedOps = validateOpenapi(committedOpenapi);
  let committedParity;
  try {
    committedParity = JSON.parse(readFileSync(join(ROOT, files.parity), 'utf8'));
  } catch {
    fail('invalid OpenAPI artifact', `${files.parity}: JSON`);
  }
  validateParity(committedParity, committedOps, committedOpenapi);
  if (process.env.API_CONTRACT_EXECUTE_EVIDENCE === '1') executeConversionEvidence(committedParity);
  if (process.env.API_CONTRACT_EXECUTE_EVIDENCE === '1') executeDirectEvidence(committedParity);
  const expected = artifactManifest({
    openapi: readFileSync(join(ROOT, files.openapi)),
    parity: readFileSync(join(ROOT, files.parity)),
    schema: readFileSync(join(ROOT, files.schema)),
    baseline: readFileSync(join(ROOT, files.baseline)),
  });
  if (JSON.stringify(canonical(manifest)) !== JSON.stringify(canonical(expected)))
    fail('contract drift', files.manifest);
  const expectedPaths = new Set(requiredManifest.map(([path]) => path));
  const discover = (dir) => {
    if (!existsSync(dir)) return [];
    return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? discover(path) : [rel(path)];
    });
  };
  const extras = discover(join(ROOT, 'apps/api/openapi')).filter(
    (path) => path !== files.manifest && !expectedPaths.has(path),
  );
  if (extras.length)
    fail('incomplete contract coverage', `unlisted artifact ${extras.sort().join(', ')}`);
  if (!Buffer.from(json(expected)).equals(readFileSync(join(ROOT, files.manifest))))
    fail('contract drift', `${files.manifest}: non-canonical ordering or newline`);
  if (!readFileSync(join(ROOT, files.schema), 'utf8').startsWith(header))
    fail('invalid OpenAPI artifact', 'schema.ts header');
  for (const key of ['openapi', 'parity', 'schema', 'manifest'])
    scanArtifact(files[key], readFileSync(join(ROOT, files[key])));
  authorityScan();
  compileGeneratedClient();
  return manifest;
}

function executeConversionEvidence(parity) {
  const result = spawnSync(
    'cargo',
    [
      'test',
      '-p',
      'api-rust',
      '--test',
      'api_contract_parity',
      'boundary_evidence_',
      '--',
      '--nocapture',
    ],
    { cwd: ROOT, encoding: 'utf8' },
  );
  const output = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
  if (result.status !== 0)
    fail('incomplete contract coverage', 'conversion evidence runner failed');
  const outcomes = new Map();
  for (const match of output.matchAll(/CONTRACT_EVIDENCE_OUTCOME ([^ \r\n]+) (\{[^\r\n]*\})/g)) {
    if (outcomes.has(match[1]))
      fail('incomplete contract coverage', `duplicate conversion outcome ${match[1]}`);
    try {
      outcomes.set(match[1], JSON.parse(match[2]));
    } catch {
      fail('incomplete contract coverage', `invalid conversion outcome ${match[1]}`);
    }
  }
  const expected = new Map(
    parity.evidence_catalog
      .filter((entry) => entry.mode === 'response-conversion')
      .map((entry) => [
        entry.test,
        { ...entry.expected_response, effect_assertion: entry.effect_assertion },
      ]),
  );
  if (outcomes.size !== expected.size || [...expected.keys()].some((id) => !outcomes.has(id)))
    fail('incomplete contract coverage', 'conversion evidence outcome set');
  for (const [id, actual] of outcomes) {
    const want = expected.get(id);
    validateEvidenceOutcome(actual, want, `conversion evidence ${id}`);
  }
}

function executeDirectEvidence(parity) {
  const commands = [
    ['api_contract_parity'],
    ['api_contract_runtime_auth_research'],
    ['api_contract_runtime_market_stream'],
  ];
  const output = commands
    .map((testTarget) => {
      const result = spawnSync(
        'cargo',
        ['test', '-p', 'api-rust', '--test', testTarget[0], '--', '--nocapture'],
        { cwd: ROOT, encoding: 'utf8' },
      );
      if (result.status !== 0)
        fail(
          'incomplete contract coverage',
          `direct HTTP evidence runner failed: ${testTarget[0]}`,
        );
      return `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
    })
    .join('\n');
  const outcomes = new Map();
  for (const match of output.matchAll(/DIRECT_HTTP_EVIDENCE_OUTCOME (.+) (\{[^\r\n]*\})/g)) {
    if (outcomes.has(match[1]))
      fail('incomplete contract coverage', `duplicate direct outcome ${match[1]}`);
    outcomes.set(match[1], JSON.parse(match[2]));
  }
  const expected = new Map(
    parity.evidence_catalog
      .filter((entry) => entry.mode === 'direct-http')
      .map((entry) => [
        entry.id,
        { ...entry.expected_response, effect_assertion: entry.effect_assertion },
      ]),
  );
  if (outcomes.size !== expected.size || [...expected.keys()].some((id) => !outcomes.has(id))) {
    const missing = [...expected.keys()].filter((id) => !outcomes.has(id));
    fail(
      'incomplete contract coverage',
      `direct HTTP evidence outcome set (${outcomes.size}/${expected.size}; missing ${missing.slice(0, 3).join(', ')})`,
    );
  }
  for (const [id, actual] of outcomes) {
    const want = expected.get(id);
    validateEvidenceOutcome(actual, want, `direct HTTP evidence ${id}`);
  }
}
export async function main(command = process.argv[2]) {
  try {
    if (command === 'generate') {
      install(candidate());
      console.log('Generated API contract artifacts.');
      return 0;
    }
    if (command === 'check') {
      check();
      const expected = candidate();
      const mismatch = [];
      for (const k of mutable) {
        const b = readFileSync(join(ROOT, files[k]));
        if (!b.equals(expected[k])) mismatch.push(files[k]);
      }
      if (mismatch.length) fail('contract drift', mismatch.join(', '));
      console.log(
        `API contract check passed: generated artifacts match the Rust API contract.\n${COVERAGE_WARNING}`,
      );
      return 0;
    }
    console.error('Usage: api-contract.mjs <generate|check>');
    return 2;
  } catch (e) {
    console.error(`${e.category ?? 'generation tooling failure'}: ${e.message}`);
    return 1;
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exit(await main());
