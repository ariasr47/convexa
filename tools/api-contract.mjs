const noMutationEffect = Object.freeze({ durable: 'none', memory: 'none', cookie: 'none' });
const mutationEffectFor = (key, status, accessMode = 'anonymous') => {
  if (
    key === 'GET /api/auth/google/start' &&
    status === 307 &&
    accessMode === 'oauth-start-success'
  )
    return { durable: 'none', memory: 'oauth-state-created', cookie: 'none' };
  if (
    key === 'GET /api/auth/google/callback' &&
    status === 307 &&
    accessMode === 'oauth-callback-success'
  )
    return { durable: 'none', memory: 'session-created', cookie: 'set' };
  if (key === 'POST /api/auth/logout' && status === 200)
    return { durable: 'none', memory: 'none', cookie: 'clear' };
  if (['POST /api/auth/signup', 'POST /api/auth/login'].includes(key) && status === 200)
    return { durable: 'user-created', memory: 'session-created', cookie: 'set' };
  // The persisted matrix intentionally uses invalid/denied/degraded inputs for mutating
  // operations.  Those paths are required to prove that no state changes leak through.
  if (accessMode !== 'anonymous' || status >= 400) return noMutationEffect;
  return noMutationEffect;
};
const exactKeys = (value, keys) =>
  value &&
  typeof value === 'object' &&
  !Array.isArray(value) &&
  JSON.stringify(Object.keys(value).sort()) === JSON.stringify([...keys].sort());
const bodyEnvelopeFor = (mediaType, status) => {
  if (status >= 300 && status < 400)
    return { body_category: 'redirect', body_valid: true, body_meaning: 'empty' };
  const body_category =
    mediaType === null
      ? 'empty'
      : mediaType === 'application/json'
        ? 'json'
        : mediaType === 'text/event-stream'
          ? 'sse'
          : mediaType === 'text/html'
            ? 'html'
            : 'text';
  return {
    body_category,
    body_valid: true,
    body_meaning: body_category === 'html' ? 'text' : body_category,
  };
};
const meaningfulHeaderNames = (response) =>
  Object.keys(response?.headers ?? {})
    .map((name) => name.toLowerCase())
    .sort();
const headerValuePoliciesFor = (operationKey, headerNames) =>
  Object.fromEntries(
    headerNames.map((name) => {
      if (name === 'set-cookie') {
        const clears = operationKey === 'POST /api/auth/logout';
        return [
          name,
          clears ? 'clear;secure;httponly;samesite=lax' : 'set;secure;httponly;samesite=lax',
        ];
      }
      if (name === 'location') return [name, 'relative-or-https'];
      if (name === 'retry-after') return [name, 'exact:30'];
      if (name === 'cache-control') return [name, 'exact:no-cache'];
      if (name === 'x-accel-buffering') return [name, 'exact:no'];
      fail('incomplete contract coverage', `unknown meaningful header policy ${name}`);
    }),
  );
const expectedResponseFor = (
  operationKey,
  status,
  mediaType,
  securityMode,
  headerNames,
  bodyValid = true,
) => {
  const normalizedHeaders = [...headerNames].map((name) => name.toLowerCase()).sort();
  const bodyEnvelope = bodyEnvelopeFor(mediaType, Number(status));
  return {
    status: Number(status),
    media_type: mediaType,
    security_mode: securityMode,
    header_names: normalizedHeaders,
    header_value_policies: headerValuePoliciesFor(operationKey, normalizedHeaders),
    ...bodyEnvelope,
    body_valid: bodyValid,
  };
};
function validateExpectedResponse(value, operationKey, allowUnobservedSse = false) {
  const expectedBody = bodyEnvelopeFor(value?.media_type, value?.status);
  if (allowUnobservedSse && value?.media_type === 'text/event-stream')
    expectedBody.body_valid = false;
  if (
    !exactKeys(value, EXPECTED_RESPONSE_KEYS) ||
    !Number.isInteger(value.status) ||
    !(value.media_type === null || typeof value.media_type === 'string') ||
    !SECURITY_MODES.includes(value.security_mode) ||
    !Array.isArray(value.header_names) ||
    new Set(value.header_names).size !== value.header_names.length ||
    value.header_names.some((name) => typeof name !== 'string' || name !== name.toLowerCase()) ||
    JSON.stringify([...value.header_names].sort()) !== JSON.stringify(value.header_names) ||
    !exactKeys(value.header_value_policies, value.header_names) ||
    JSON.stringify(value.header_value_policies) !==
      JSON.stringify(headerValuePoliciesFor(operationKey, value.header_names)) ||
    JSON.stringify({
      body_category: value.body_category,
      body_valid: value.body_valid,
      body_meaning: value.body_meaning,
    }) !== JSON.stringify(expectedBody)
  )
    fail('incomplete contract coverage', `expected response envelope ${operationKey}`);
}
function validateEffectAssertion(value, operationKey, status, mode, accessMode) {
  if (
    !exactKeys(value, EFFECT_ASSERTION_KEYS) ||
    !['none', 'user-created'].includes(value.durable) ||
    !['none', 'session-created', 'oauth-state-created'].includes(value.memory) ||
    !['none', 'set', 'clear'].includes(value.cookie)
  )
    fail('incomplete contract coverage', `effect assertion ${operationKey}`);
  const expected =
    mode === 'response-conversion'
      ? noMutationEffect
      : mutationEffectFor(
          operationKey,
          status,
          accessMode ?? (status === 200 ? 'success' : 'anonymous'),
        );
  if (JSON.stringify(canonical(value)) !== JSON.stringify(canonical(expected)))
    fail('incomplete contract coverage', `effect assertion drift ${operationKey}`);
}
